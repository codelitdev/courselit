import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { oauthProvider } from "@better-auth/oauth-provider";
import { createOAuthProviderOptions } from "@codelitdev/oauth-server-kit/better-auth";
import { getSchema } from "better-auth/db";
import { emailOTP } from "better-auth/plugins/email-otp";
import { jwt } from "better-auth/plugins/jwt";
import { sso } from "@better-auth/sso";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const tsPath = path.join(root, "src/db/schema/auth.generated.ts");
const sqlPath = path.join(root, "src/db/migrations/0000_auth.sql");
const check = process.argv.includes("--check");

const publicApiUrl = "http://127.0.0.1:4000";
const options = {
  appName: "CourseLit",
  baseURL: publicApiUrl,
  basePath: "/api/auth",
  secret: "schema-generation-secret-at-least-32-chars",
  emailAndPassword: { enabled: true },
  plugins: [
    jwt(),
    emailOTP({
      async sendVerificationOTP() {},
    }),
    oauthProvider(
      createOAuthProviderOptions({
        loginPage: `${publicApiUrl}/oauth/login`,
        consentPage: `${publicApiUrl}/oauth/consent`,
        scopes: ["openid", "profile", "email", "offline_access", "data:read"],
        validAudiences: [`${publicApiUrl}/api`, `${publicApiUrl}/mcp`],
        clientRegistrationDefaultScopes: ["openid", "profile", "email"],
        clientRegistrationAllowedScopes: ["offline_access", "data:read"],
      }),
    ),
    sso({
      fields: {
        domain: "domain_string",
      },
    }),
  ],
};

const schema = getSchema(options);

function snake(value) {
  return value
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .replace(/([a-z\d])([A-Z])/g, "$1_$2")
    .replace(/-/g, "_")
    .toLowerCase();
}

function toCamel(name) {
  return name.replace(/[_-](\w)/g, (_, ch) => ch.toUpperCase());
}

function quoteIdent(name) {
  return `"${name.replaceAll('"', '""')}"`;
}

function drizzleType(sqlCol, field) {
  const type = field.type;
  if (type === "boolean") return `boolean("${sqlCol}")`;
  if (type === "number") return `integer("${sqlCol}")`;
  if (type === "date") return `timestamp("${sqlCol}", { withTimezone: true })`;
  if (type === "json") return `jsonb("${sqlCol}")`;
  if (type === "string[]" || (Array.isArray(type) && type[0] === "string")) {
    return `text("${sqlCol}").array()`;
  }
  return `text("${sqlCol}")`;
}

function sqlType(field) {
  const type = field.type;
  if (type === "boolean") return "boolean";
  if (type === "number") return "integer";
  if (type === "date") return "timestamptz";
  if (type === "json") return "jsonb";
  if (type === "string[]" || (Array.isArray(type) && type[0] === "string")) {
    return "text[]";
  }
  return "text";
}

const tables = Object.entries(schema)
  .filter(([, table]) => !table.disableMigrations)
  .sort((a, b) => {
    const order = (a[1].order ?? 1000) - (b[1].order ?? 1000);
    return order !== 0 ? order : a[0].localeCompare(b[0]);
  });

const ts = [
  "/**",
  " * AUTO-GENERATED FILE. DO NOT EDIT.",
  " * Generated by Better Auth getSchema (better-auth/db) from the reference",
  " * Better Auth options (jwt + oauth-server-kit oauthProvider).",
  " * Importing this module performs no DDL.",
  " */",
  'import { boolean, integer, jsonb, pgTable, text, timestamp } from "drizzle-orm/pg-core";',
  "",
];
const sql = ["-- AUTO-GENERATED by scripts/generate-auth-schema.mjs. DO NOT EDIT."];

for (const [modelName, table] of tables) {
  const exportName = toCamel(modelName);
  const tableSql = snake(modelName);
  ts.push(`export const ${exportName} = pgTable("${tableSql}", {`);
  ts.push('        id: text("id").primaryKey(),');
  if (sql.length > 1) sql.push("--> statement-breakpoint");
  sql.push(`CREATE TABLE IF NOT EXISTS ${quoteIdent(tableSql)} (`);
  const sqlCols = [`  id text PRIMARY KEY`];
  for (const [key, field] of Object.entries(table.fields)) {
    const sqlCol = snake(field.fieldName || key);
    let col = drizzleType(sqlCol, field);
    let sqlDef = `  ${quoteIdent(sqlCol)} ${sqlType(field)}`;
    if (field.required === true) {
      col += ".notNull()";
      sqlDef += " NOT NULL";
    }
    if (field.unique) {
      col += ".unique()";
      sqlDef += " UNIQUE";
    }
    if (field.references) {
      const targetTable = snake(field.references.model);
      const targetField = snake(field.references.field || "id");
      const onDelete = field.references.onDelete ?? "cascade";
      const targetExport = toCamel(field.references.model);
      const targetProp = toCamel(field.references.field || "id");
      col += `.references(() => ${targetExport}.${targetProp}, { onDelete: "${onDelete}" })`;
      sqlDef += ` REFERENCES ${quoteIdent(targetTable)}(${quoteIdent(targetField)}) ON DELETE ${onDelete.toUpperCase()}`;
    }
    ts.push(`        ${toCamel(key)}: ${col},`);
    sqlCols.push(sqlDef);
  }
  ts.push("});");
  ts.push("");
  sql.push(`${sqlCols.join(",\n")}`);
  sql.push(");");
}

const tsSource = `${ts.join("\n").trimEnd()}\n`;
const sqlSource = `${sql.join("\n")}\n`;

function writeOrCheck(filePath, source) {
  let existing;
  try {
    existing = readFileSync(filePath, "utf8");
  } catch {
    // A missing generated file is reported as drift below.
  }
  if (check) {
    if (existing !== source) {
      const fp = (value) => createHash("sha256").update(value).digest("hex");
      process.stderr.write(
        `auth schema drift: ${filePath}\ncommitted=${existing ? fp(existing) : "missing"} generated=${fp(source)}\n`,
      );
      process.exitCode = 1;
      return false;
    }
    process.stdout.write(`ok ${filePath}\n`);
    return true;
  }
  if (existing !== source) {
    writeFileSync(filePath, source);
    process.stdout.write(`wrote ${filePath}\n`);
  } else {
    process.stdout.write(`unchanged ${filePath}\n`);
  }
  return true;
}

const tsOk = writeOrCheck(tsPath, tsSource);
const sqlOk = writeOrCheck(sqlPath, sqlSource);
if (check && (!tsOk || !sqlOk)) process.exit(1);
